#!/usr/bin/env node
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { isScriptEntry } from './script-entry.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixturePath = 'test/fixtures/svelte4';
const exact = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
const commands = [
	'npm ci --install-links',
	'npm exec -- svelte-adapter-uws-preflight',
	'npm exec -- playwright install --with-deps chromium',
	'npm run build', 'npm run check', 'npm run stores', 'npm run smoke'
];

export function readProfile(directory = root) {
	const json = (path) => JSON.parse(readFileSync(resolve(directory, path), 'utf8'));
	return {
		pkg: json(fixturePath + '/package.json'),
		lock: json(fixturePath + '/package-lock.json'),
		owner: json('package.json'),
		node: readFileSync(resolve(directory, fixturePath, '.nvmrc'), 'utf8').trim()
	};
}

export function validateProfile({ pkg, lock, owner, node }) {
	assert.deepEqual(pkg.scripts, { check: 'svelte-kit sync && svelte-check --tsconfig ./jsconfig.json', build: 'svelte-kit sync && vite build', stores: 'node stores.mjs', smoke: 'node smoke.mjs' }, 'Fixture verification scripts drifted');
	assert.match(node, exact, 'Fixture Node version must be exact');
	assert.equal(pkg.engines.node, '>=' + node, 'Fixture engine must match its tested Node floor');
	assert.equal(pkg.dependencies['svelte-realtime'], 'file:../../..', 'Fixture must test the current checkout');
	for (const section of ['dependencies', 'devDependencies']) {
		assert.deepEqual(lock.packages[''][section], pkg[section], 'Fixture manifest/lock drift in ' + section);
		for (const [name, version] of Object.entries(pkg[section])) {
			if (name === 'svelte-realtime') continue;
			assert.match(version, exact, name + ' must be an exact version');
			assert.equal(lock.packages['node_modules/' + name]?.version, version, name + ' lock version drift');
		}
	}
	assert.match(pkg.dependencies.svelte, /^4\./, 'Fixture must remain on Svelte 4');
	const packed = lock.packages['node_modules/svelte-realtime'];
	assert.ok(packed && !packed.link, 'Install with --install-links to test a packed checkout');
	assert.equal(packed.resolved, 'file:../../..', 'Packed fixture must resolve this checkout rather than a registry artifact');
	assert.equal(packed.version, owner.version, 'Packed checkout version drift: regenerate the fixture lock');
	for (const field of ['dependencies', 'peerDependencies', 'optionalDependencies', 'peerDependenciesMeta', 'engines', 'bin']) {
		const expected = owner[field] ?? {};
		const actual = packed[field] ?? {};
		assert.deepEqual(actual, field === 'bin' ? Object.fromEntries(Object.entries(expected).map(([key, value]) => [key, value.replace(/^\.\//, '')])) : expected, 'Packed checkout metadata drift: ' + field);
	}
}

export function validateWorkflow(workflow) {
	const job = workflow.jobs?.svelte4;
	assert.equal(job?.defaults?.run?.['working-directory'], fixturePath, 'Svelte 4 CI must run inside its fixture');
	assert.equal(job.steps.find((step) => step.uses?.startsWith('actions/setup-node@'))?.with?.['node-version-file'], fixturePath + '/.nvmrc');
	assert.deepEqual(job.steps.filter((step) => step.run).map((step) => step.run), commands, 'Svelte 4 install/preflight/build/type/store/browser CI gates drifted');
}

export function trackedArtifacts(directory = root) {
	return execFileSync('git', ['ls-files', '-z'], { cwd: directory, encoding: 'utf8', windowsHide: true })
		.split('\0').filter((path) => /(?:^|\/)(?:build|\.svelte-kit|node_modules)\//.test(path));
}

export function renderSupport(profile) {
	const { pkg, node, owner } = profile;
	const all = { ...pkg.dependencies, ...pkg.devDependencies };
	return '# Locked Svelte 4 support\n\n' +
		'This profile tests the current realtime checkout as an installed package. It covers RPC, ordinary stream stores, production SSR, browser updates and declaration checking. Svelte 5 rune features remain outside this profile; see [version compatibility](../README.md#version-compatibility).\n\n' +
		'<!-- Generated by scripts/check-svelte-support.js from the fixture manifest and lockfile. -->\n' +
		'| Node | Svelte | SvelteKit | Vite | Svelte Vite plugin | svelte-check | Adapter | Realtime |\n' +
		'|---|---|---|---|---|---|---|---|\n' +
		'| ' + [node, all.svelte, all['@sveltejs/kit'], all.vite, all['@sveltejs/vite-plugin-svelte'], all['svelte-check'], all['svelte-adapter-uws'], owner.version + ' (checkout)'].join(' | ') + ' |\n\n' +
		'Use Node ' + node + ' from the fixture .nvmrc, then run these commands from the repository root:\n\n' +
		'~~~sh\ncd ' + fixturePath + '\n' + commands.join('\n') + '\n~~~\n\n' +
		'Build precedes type checking because the realtime Vite plugin generates the $live declarations. The store check verifies subscribe/hydrate/map plus the explicit Svelte 5-only rune boundary. The browser check starts the production build on a free loopback port, checks two tabs and reload, then stops the server. Its demo identity accepts local test clients; it is not deployment authentication.\n\n' +
		'The dedicated Svelte 4 CI job runs beside the existing Svelte 5 verification and browser fixtures. npm ci --install-links installs the locked dependencies and packages this checkout, rather than resolving a published realtime version. This is a framework compatibility check, not a claim that a new coordinated release tuple has been published.\n\n' +
		'When changing package dependencies, regenerate this fixture lock with npm install --package-lock-only --install-links --ignore-scripts inside the fixture, then run node scripts/check-svelte-support.js --write from the repository root and repeat all checks above. The root check gate rejects manifest, lockfile, generated documentation and CI drift, plus tracked build/.svelte-kit/node_modules artifacts at any directory depth.\n';
}

export function checkSupport(directory = root, write = false) {
	const profile = readProfile(directory);
	validateProfile(profile);
	validateWorkflow(parse(readFileSync(resolve(directory, '.github/workflows/verify.yml'), 'utf8')));
	assert.deepEqual(trackedArtifacts(directory), [], 'Generated build/dependency artifacts must not be tracked');
	const output = renderSupport(profile);
	const target = resolve(directory, 'docs/svelte-support.md');
	if (write) writeFileSync(target, output);
	assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, 'Svelte support docs stale: run node scripts/check-svelte-support.js --write');
}

if (isScriptEntry(import.meta.url)) {
	try { checkSupport(root, process.argv.includes('--write')); console.log('Svelte 4 support profile, docs, CI and artifact guard agree'); }
	catch (error) { console.error(error.message); process.exitCode = 1; }
}
