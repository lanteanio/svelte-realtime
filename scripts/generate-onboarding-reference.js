#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SCAFFOLD_ADAPTER_SPEC,
  SCAFFOLD_AUTH_WARNING,
  SCAFFOLD_EXTENSIONS_SPEC,
  SCAFFOLD_REALTIME_SPEC,
  SCAFFOLD_UWS_SPEC,
  renderFirstRunTranscript,
} from "../src/cli-utils.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "docs", "first-run.md");
const docsSiteTarget = resolve(
  root,
  "..",
  "svelte-realtime-docs",
  "src",
  "lib",
  "generated",
  "onboarding-contract.ts",
);

export function renderOnboardingReference() {
  const warning = SCAFFOLD_AUTH_WARNING;
  return `# Accepted first-run transcript

This generated page is the release acceptance contract for the non-interactive
newcomer route. Edit \`src/cli-utils.js\`, then regenerate; do not edit this page
by hand.

## Audited candidate tuple

- \`${SCAFFOLD_ADAPTER_SPEC}\`
- \`${SCAFFOLD_REALTIME_SPEC}\`
- \`${SCAFFOLD_EXTENSIONS_SPEC}\`
- \`${SCAFFOLD_UWS_SPEC}\`

The candidate versions must be published together before the registry command
is executable. Publication is deliberately separate from implementation review.

## Clean transcript

\`\`\`text
${renderFirstRunTranscript()}
\`\`\`

The authentication warning is expected on the first browser connection until
the scaffold placeholder is replaced. No missing-message, ignored-config, native
ABI, or failed-build warning is accepted in this transcript.

## Warning contract

- Code: \`${warning.code}\`
- Title: ${warning.title}
- Body: ${warning.body}
`;
}

export function renderDocsSiteContract() {
  const warning = SCAFFOLD_AUTH_WARNING;
  const quote = (value) =>
    "'" +
    value
      .replaceAll("\\", "\\\\")
      .replaceAll("'", "\\'")
      .replaceAll("\r", "\\r")
      .replaceAll("\n", "\\n") +
    "'";
  return `// Generated by svelte-realtime/scripts/generate-onboarding-reference.js.
// Do not edit this mirror; the CLI-owned contract is the source of truth.
export const ADAPTER_SPEC = ${quote(SCAFFOLD_ADAPTER_SPEC)};
export const REALTIME_SPEC = ${quote(SCAFFOLD_REALTIME_SPEC)};
export const EXTENSIONS_SPEC = ${quote(SCAFFOLD_EXTENSIONS_SPEC)};
export const UWS_SPEC = ${quote(SCAFFOLD_UWS_SPEC)};
export const AUTH_WARNING = Object.freeze({
\tcode: ${quote(warning.code)},
\ttitle: ${quote(warning.title)},
\tbody: ${quote(warning.body)},
\tline: ${quote("[" + warning.code + "] " + warning.title + ": " + warning.body)}
});
export const FIRST_RUN_TRANSCRIPT =
\t${quote(renderFirstRunTranscript())};
`;
}

export function main(args = process.argv.slice(2)) {
  const expected = renderOnboardingReference();
  const write = args.includes("--write");
  const syncDocsSite = args.includes("--sync-docs-site");
  if (write) {
    writeFileSync(target, expected);
    console.log("generate-onboarding-reference: wrote docs/first-run.md");
  } else {
    const actual = readFileSync(target, "utf8");
    if (actual !== expected) {
      console.error(
        "generate-onboarding-reference FAILED: docs/first-run.md is stale; run node scripts/generate-onboarding-reference.js --write",
      );
      process.exitCode = 1;
    } else {
      console.log(
        "generate-onboarding-reference: accepted transcript is current",
      );
    }
  }

  if (existsSync(dirname(docsSiteTarget))) {
    const expectedDocsSite = renderDocsSiteContract();
    if (syncDocsSite) {
      writeFileSync(docsSiteTarget, expectedDocsSite);
      console.log(
        "generate-onboarding-reference: synced docs-site onboarding contract",
      );
    } else if (
      !existsSync(docsSiteTarget) ||
      readFileSync(docsSiteTarget, "utf8") !== expectedDocsSite
    ) {
      // The docs site owns its mirror and verifies it with its own
      // check:onboarding gate against this generator, so a stale sibling
      // checkout is that repository's signal to sync, not a failure of this
      // one: this gate must stay green on a clone with no sibling at all.
      console.warn(
        "generate-onboarding-reference: docs-site onboarding mirror is stale; sync it from the docs repository with --sync-docs-site",
      );
    }
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
